#!/usr/bin/env python
# gen_policy.py — 生成 src/policy_inc.h（模拟 360 native 层携带的"策略/签名表"）
#
# 目的：
#   1) 给样本提供可观的可压缩体积，让 UPX（360 native 壳的历史基础）有"净收益"可打包
#      （UPX 自带 ~3.5KB stub，原始 .so 太小会触发 NotCompressibleException，见 README §7）。
#   2) 这部分数据是脱壳后可逐字节对照的"真实数据锚点"，不是随机填充。
#
# 用法：由 build_android.sh 自动调用；也可单独运行  python build/gen_policy.py
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "policy_inc.h")
N = 1000  # 1000 条 -> 约 45KB 文本，原始 .so 总体积 ~50KB，UPX 可稳定打包

lines = []
for i in range(N):
    h = format((i * 2654435761) & 0xFFFFFFFF, "08x")
    mode = "allow" if (i % 3) else "deny"
    pkg = "com.aegis.%s" % ("core" if i % 2 == 0 else "svc%d" % (i % 97))
    lines.append('"pol:%04d:%s:%s:%s\\n"' % (i, mode, pkg, h))

header = (
    "/* AUTO-GENERATED by build/gen_policy.py -- 不要手改 */\n"
    "/* 模拟 360 native 层携带的策略/签名表：提供可观的可压缩体积（让 UPX 有净收益），\n"
    "   同时是脱壳后可逐字节对照的真实数据锚点。 */\n"
    "static const char POLICY_BLOB[] =\n  "
    + "\n  ".join(lines)
    + ";\n"
    "static const int POLICY_BLOB_LEN = (int)(sizeof(POLICY_BLOB) - 1);\n"
)
with open(OUT, "w") as f:
    f.write(header)
print("[+] wrote %s (%d entries, %d bytes of policy text)" % (OUT, N, len("".join(lines))))
